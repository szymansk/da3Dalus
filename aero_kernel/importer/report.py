"""The generated ``IMPORT_REPORT.md`` and the stable text of ``canon_model.json`` (ch. 8.7, 8.9)."""

import json

from aero_kernel.canon.model import CanonModel
from aero_kernel.errors import DEFAULT_NAMESPACE

__all__ = ["model_text", "report_text"]


def model_text(model: CanonModel) -> str:
    """Serialise the model as stable text: sorted keys, two-space indent, trailing newline."""
    return (
        json.dumps(model.model_dump(mode="json"), indent=2, sort_keys=True, ensure_ascii=False)
        + "\n"
    )


def report_text(model: CanonModel) -> str:
    """Render the import report: provenance, counts and the table of formulas (Appendix A).

    The report holds no timestamp and no path, so importing the same canon twice gives the same
    bytes. A formula of cost class ``minutes`` is long-running (ch. 8.7); the cost column says so.

    Args:
        model: The imported model.

    Returns:
        The Markdown text.
    """
    content = model.namespaces[DEFAULT_NAMESPACE]
    lines = [
        "# Canon import report",
        "",
        "Generated by `python -m aero_kernel.importer`; do not edit.",
        "",
        f"- source commit: `{model.source_commit}`",
        f"- importer version: `{model.importer_version}`",
        f"- content hash: `{model.content_hash}`",
        f"- formulas: {len(content.formulas)}",
        f"- quantities: {len(content.quantities)}",
        f"- defaults: {len(content.defaults)}",
        "",
        "## Appendix A: formulas",
        "",
        "A formula with cost class `minutes` is long-running and runs only on request (ch. 8.7).",
        "",
        "| formula | kind | tool | cost | applications |",
        "|---|---|---|---|---|",
    ]
    lines.extend(
        f"| {slug} | {formula.kind} | {formula.tool} | {formula.cost} | "
        f"{', '.join(application.id for application in formula.applications)} |"
        for slug, formula in sorted(content.formulas.items())
    )
    return "\n".join(lines) + "\n"
